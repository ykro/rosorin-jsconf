#!/usr/bin/env node
// Generates src/lib/gesture-choreographies.generated.ts from robot-bridge/src/gestures.rs,
// so the browser-only simulator plays the same multi-step choreographies as the Rust bridge.
// Usage: node scripts/gen-gestures.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const RUST_SRC = resolve(here, '../../robot-bridge/src/gestures.rs');
const OUT = resolve(here, '../src/lib/gesture-choreographies.generated.ts');

export function parseGestures(rust) {
  const body = rust.slice(rust.indexOf('pub fn get_gesture'), rust.indexOf('#[cfg(test)]'));
  const armRe = /((?:"[a-z_]+"\s*\|\s*)*"[a-z_]+"|_)\s*=>\s*GestureSequence\s*\{/g;
  const arms = [];
  let m;
  while ((m = armRe.exec(body))) arms.push({ keys: m[1], start: m.index, bodyStart: armRe.lastIndex });
  const gestures = {};
  const aliases = {};
  arms.forEach((arm, i) => {
    const chunk = body.slice(arm.bodyStart, i + 1 < arms.length ? arms[i + 1].start : body.length);
    // Canonical id = first key of the match arm (the `_` arm is home).
    const name = arm.keys === '_' ? 'home' : /"([a-z_]+)"/.exec(arm.keys)[1];
    const rgb = /rgb:\s*\((\d+),\s*(\d+),\s*(\d+)\)/.exec(chunk).slice(1, 4).map(Number);
    const stepRe =
      /duration_ms:\s*(\d+),\s*servos:\s*pose\(([^)]*)\),[^\n]*\n\s*velocity:\s*(None|Some\(\(([^)]*)\)\))/g;
    const steps = [];
    let s;
    while ((s = stepRe.exec(chunk))) {
      steps.push({
        durationMs: Number(s[1]),
        servos: s[2].split(',').map((v) => Number(v.trim())),
        velocity: s[4] ? s[4].split(',').map((v) => Number(v.trim())) : null,
      });
    }
    if (steps.length === 0) throw new Error(`gesture ${name}: no steps parsed`);
    gestures[name] = { rgb, steps };
    if (arm.keys !== '_') {
      for (const key of arm.keys.match(/"([a-z_]+)"/g).map((k) => k.slice(1, -1))) aliases[key] = name;
    }
  });
  for (const key of ['home', 'reset', 'neutral']) aliases[key] = 'home';
  return { gestures, aliases };
}

export function renderModule({ gestures, aliases }) {
  return `// Generated by scripts/gen-gestures.mjs from robot-bridge/src/gestures.rs. Do not edit by hand.
// Run \`npm run gen:gestures\` after changing a choreography in Rust.

export interface GestureStepData {
  durationMs: number;
  /** Pulses for servos 1, 2, 3, 4, 5 and 10 (gripper). */
  servos: [number, number, number, number, number, number];
  /** (linear_x, linear_y, angular_z) held during the step, or null to keep the previous one. */
  velocity: [number, number, number] | null;
}

export interface GestureData {
  rgb: [number, number, number];
  steps: GestureStepData[];
}

export const GESTURE_ALIASES: Record<string, string> = ${JSON.stringify(aliases, null, 2)};

export const GESTURES: Record<string, GestureData> = ${JSON.stringify(gestures, null, 2)};
`;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const out = renderModule(parseGestures(readFileSync(RUST_SRC, 'utf8')));
  if (process.argv.includes('--check')) {
    if (readFileSync(OUT, 'utf8') !== out) {
      console.error('gesture-choreographies.generated.ts is stale: run `npm run gen:gestures`.');
      process.exit(1);
    }
    console.log('gen:gestures OK: generated module matches gestures.rs.');
  } else {
    writeFileSync(OUT, out);
    console.log(`Wrote ${OUT}`);
  }
}
